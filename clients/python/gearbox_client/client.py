"""Gearbox sidecar client: one channel, a deadline per call, a fallback value."""

from __future__ import annotations

import json
import os
import uuid
from dataclasses import dataclass, field
from typing import Any, Optional

import grpc

try:  # generated by scripts/gen.sh
    from gearbox.v1 import engine_pb2, engine_pb2_grpc
except ImportError as exc:  # pragma: no cover - only when stubs are missing
    raise ImportError(
        "Gearbox stubs not found. Generate them with clients/python/scripts/gen.sh "
        "(pip install grpcio-tools) and install this package again."
    ) from exc

DEFAULT_TARGET = "unix:///var/run/gearbox/engine.sock"

# Codes where the sidecar could not give an answer: use the fallback.
_FALLBACK_CODES = {
    grpc.StatusCode.UNAVAILABLE,
    grpc.StatusCode.DEADLINE_EXCEEDED,
    grpc.StatusCode.FAILED_PRECONDITION,  # NOT_READY
    grpc.StatusCode.NOT_FOUND,  # DECISION_NOT_FOUND
    grpc.StatusCode.INTERNAL,  # NODE_ERROR without a decision fallback
}


class GearboxError(Exception):
    """A call failed and no fallback applies (for example INPUT_SCHEMA)."""

    def __init__(self, code: grpc.StatusCode, message: str):
        super().__init__(f"{code.name}: {message}")
        self.code = code
        self.message = message


@dataclass
class Decision:
    output: Any
    version: str = ""
    dependency_hash: str = ""
    generation: int = 0
    fallback_used: bool = False
    from_client_fallback: bool = False
    request_id: str = ""
    path: list = field(default_factory=list)


class Client:
    """Reuse one Client per process; it multiplexes calls over one channel."""

    def __init__(self, target: Optional[str] = None, default_timeout: float = 0.005):
        self._target = target or os.environ.get("GEARBOX_TARGET", DEFAULT_TARGET)
        self._channel = grpc.insecure_channel(self._target)
        self._stub = engine_pb2_grpc.EngineServiceStub(self._channel)
        self._default_timeout = default_timeout

    def close(self) -> None:
        self._channel.close()

    def __enter__(self) -> "Client":
        return self

    def __exit__(self, *exc) -> None:
        self.close()

    def decide(
        self,
        decision: str,
        input: Any,
        *,
        unit_id: str = "",
        request_id: Optional[str] = None,
        timeout: Optional[float] = None,
        fallback: Any = None,
        trace: bool = False,
    ) -> Decision:
        """Evaluate one decision. Returns `fallback` (from_client_fallback=True)
        when the sidecar cannot answer; raises GearboxError for caller errors."""
        rid = request_id or uuid.uuid4().hex
        req = engine_pb2.DecideRequest(
            decision=decision,
            input_json=json.dumps(input, separators=(",", ":")).encode(),
            request_id=rid,
            unit_id=unit_id,
            options=engine_pb2.DecideOptions(trace=trace),
        )
        try:
            resp = self._stub.Decide(
                req,
                timeout=timeout if timeout is not None else self._default_timeout,
                metadata=(("x-request-id", rid),),
            )
        except grpc.RpcError as err:
            code = err.code()
            if fallback is not None and code in _FALLBACK_CODES:
                return Decision(output=fallback, from_client_fallback=True, request_id=rid)
            raise GearboxError(code, err.details() or "") from err
        return Decision(
            output=json.loads(resp.output_json) if resp.output_json else None,
            version=resp.decision_version,
            dependency_hash=resp.dependency_hash,
            generation=resp.bundle_generation,
            fallback_used=resp.fallback_used,
            request_id=resp.request_id,
            path=[(s.node_id, s.node_type, s.outcome) for s in resp.path],
        )

    def check_gate(self, gate: str, unit_id: str = "", attributes: Optional[dict] = None,
                   *, timeout: Optional[float] = None, fallback: Optional[bool] = None) -> bool:
        try:
            resp = self._stub.CheckGate(
                engine_pb2.CheckGateRequest(
                    gate=gate, unit_id=unit_id,
                    attributes_json=json.dumps(attributes or {}).encode()),
                timeout=timeout if timeout is not None else self._default_timeout)
            return resp.value
        except grpc.RpcError as err:
            if fallback is not None and err.code() in _FALLBACK_CODES:
                return fallback
            raise GearboxError(err.code(), err.details() or "") from err

    def get_variant(self, experiment: str, unit_id: str, attributes: Optional[dict] = None,
                    *, timeout: Optional[float] = None):
        """Returns the raw GetVariantResponse (variant, parameters_json, reason...)."""
        return self._stub.GetVariant(
            engine_pb2.GetVariantRequest(
                experiment=experiment, unit_id=unit_id,
                attributes_json=json.dumps(attributes or {}).encode()),
            timeout=timeout if timeout is not None else self._default_timeout)
