#!/usr/bin/env python3
"""Generate TypeScript types and typed operation functions from the Gearbox OpenAPI contract.

Usage: python3 scripts/gen-api.py [path/to/gearbox-admin.v1.yaml]

Writes:
  src/lib/api/types.gen.ts       one TS type per components/schemas entry
  src/lib/api/operations.gen.ts  one typed function per operationId, plus the `Ops` map used by the mock

Only python3 + PyYAML are needed (no npm), so the client can be regenerated anywhere.
"""
from __future__ import annotations

import json
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
UI = os.path.dirname(HERE)
DEFAULT_SPEC = os.path.join(UI, '..', 'contracts', 'openapi', 'gearbox-admin.v1.yaml')
OUT_DIR = os.path.join(UI, 'src', 'lib', 'api')

IDENT = re.compile(r'^[A-Za-z_$][A-Za-z0-9_$]*$')
HEADER = (
    '// Code generated by ui/scripts/gen-api.py from contracts/openapi/gearbox-admin.v1.yaml. DO NOT EDIT.\n'
    '// Regenerate with `npm run gen:api`.\n'
    '/* eslint-disable */\n'
)


def prop_key(name: str) -> str:
    return name if IDENT.match(name) else json.dumps(name)


def ref_name(ref: str) -> str:
    return ref.rsplit('/', 1)[-1]


def jsdoc(text: str | None, indent: str = '') -> str:
    if not text:
        return ''
    lines = [l.rstrip() for l in str(text).strip().splitlines()]
    lines = [l.replace('*/', '*\\/') for l in lines]
    if len(lines) == 1:
        return f'{indent}/** {lines[0]} */\n'
    body = ''.join(f'{indent} * {l}\n' if l else f'{indent} *\n' for l in lines)
    return f'{indent}/**\n{body}{indent} */\n'


def literal(v) -> str:
    if v is None:
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    return json.dumps(v)


class Gen:
    def __init__(self, spec: dict, prefix: str = ''):
        self.spec = spec
        self.schemas = spec.get('components', {}).get('schemas', {})
        self.prefix = prefix

    def ref(self, ref: str) -> str:
        return self.prefix + ref_name(ref)

    def paren(self, t: str) -> str:
        return f'({t})' if ('|' in t or '&' in t) and not (t.startswith('{') and t.endswith('}')) else t

    def type_expr(self, s, indent: str = '') -> str:
        if s is None or s is True or s == {}:
            return 'unknown'
        if s is False:
            return 'never'
        if '$ref' in s:
            return self.ref(s['$ref'])
        if 'oneOf' in s or 'anyOf' in s:
            parts = [self.type_expr(x, indent) for x in (s.get('oneOf') or s.get('anyOf'))]
            return ' | '.join(self.paren(p) for p in parts)
        if 'allOf' in s:
            parts = [self.type_expr(x, indent) for x in s['allOf']]
            return ' & '.join(self.paren(p) for p in parts)
        if 'const' in s:
            return literal(s['const'])
        if 'enum' in s:
            return ' | '.join(literal(v) for v in s['enum'])
        t = s.get('type')
        types = t if isinstance(t, list) else ([t] if t else [])
        if not types:
            if 'properties' in s or 'additionalProperties' in s:
                types = ['object']
            elif 'items' in s:
                types = ['array']
            else:
                return 'unknown'
        out = []
        for one in types:
            if one == 'object':
                out.append(self.object_expr(s, indent))
            elif one == 'array':
                out.append(self.paren(self.type_expr(s.get('items'), indent)) + '[]')
            elif one in ('integer', 'number'):
                out.append('number')
            elif one == 'string':
                out.append('string')
            elif one == 'boolean':
                out.append('boolean')
            elif one == 'null':
                out.append('null')
            else:
                out.append('unknown')
        return ' | '.join(out)

    def object_body(self, s, indent: str) -> list[str]:
        props = s.get('properties') or {}
        req = set(s.get('required') or [])
        inner = indent + '  '
        lines = []
        for name, ps in props.items():
            doc = ps.get('description') if isinstance(ps, dict) else None
            if doc and '$ref' not in ps:
                lines.append(jsdoc(doc, inner).rstrip('\n'))
            opt = '' if name in req else '?'
            ro = 'readonly ' if isinstance(ps, dict) and ps.get('readOnly') else ''
            lines.append(f'{inner}{ro}{prop_key(name)}{opt}: {self.type_expr(ps, inner)};')
        ap = s.get('additionalProperties')
        if ap not in (None, False):
            if props:
                lines.append(f'{inner}[key: string]: unknown;')
            else:
                lines.append(f'{inner}[key: string]: {self.type_expr(ap if isinstance(ap, dict) else {}, inner)};')
        return lines

    def object_expr(self, s, indent: str) -> str:
        props = s.get('properties') or {}
        ap = s.get('additionalProperties')
        if not props:
            if isinstance(ap, dict) and ap:
                return f'Record<string, {self.type_expr(ap, indent)}>'
            return 'Record<string, unknown>'
        lines = self.object_body(s, indent)
        return '{\n' + '\n'.join(lines) + f'\n{indent}}}'

    # ---------- named schemas
    def named(self, name: str, s: dict) -> str:
        doc = jsdoc(s.get('description'))
        if 'allOf' in s and len(s['allOf']) == 2 and '$ref' in s['allOf'][0] and '$ref' not in s['allOf'][1]:
            base = ref_name(s['allOf'][0]['$ref'])
            ext = s['allOf'][1]
            base_schema = self.schemas.get(base, {})
            base_props = set((base_schema.get('properties') or {}).keys())
            own = set((ext.get('properties') or {}).keys())
            overridden = sorted(base_props & own)
            extra_required = [r for r in ext.get('required') or [] if r not in own and r in base_props]
            omit = sorted(set(overridden) | set(extra_required))
            parent = f'Omit<{base}, {" | ".join(json.dumps(o) for o in omit)}>' if omit else base
            lines = self.object_body(ext, '')
            for r in extra_required:
                lines.append(f'  {prop_key(r)}: NonNullable<{base}[{json.dumps(r)}]>;')
            return f'{doc}export interface {name} extends {parent} {{\n' + '\n'.join(lines) + '\n}\n'
        is_obj = (s.get('type') == 'object' or ('properties' in s and 'type' not in s)) and s.get('properties') and 'oneOf' not in s
        if is_obj:
            lines = self.object_body(s, '')
            return f'{doc}export interface {name} {{\n' + '\n'.join(lines) + '\n}\n'
        return f'{doc}export type {name} = {self.type_expr(s)};\n'

    def types_file(self) -> str:
        out = [HEADER]
        for name, s in self.schemas.items():
            out.append(self.named(name, s))
        # helpers for the discriminated node union and conditions
        if 'Node' in self.schemas:
            out.append("/** Every node type, from the `Node` discriminator. */\nexport type NodeType = Node['type'];\n")
            out.append('/** Narrow `Node` by its `type`. */\nexport type NodeOf<K extends NodeType> = Extract<Node, { type: K }>;\n')
            mapping = self.schemas['Node'].get('discriminator', {}).get('mapping', {})
            out.append('export const NODE_TYPES = ' + json.dumps(list(mapping.keys())) + ' as const satisfies readonly NodeType[];\n')
        for name, s in self.schemas.items():
            if 'enum' in s and s.get('type') == 'string':
                out.append(f'export const {name}Values = {json.dumps(s["enum"])} as const satisfies readonly {name}[];\n')
        return '\n'.join(out)


METHODS = ('get', 'post', 'put', 'patch', 'delete')


def upper_first(s: str) -> str:
    return s[0].upper() + s[1:]


def ops_file(spec: dict) -> str:
    g = Gen(spec, prefix='T.')
    comp_params = spec.get('components', {}).get('parameters', {})

    def resolve_param(p):
        if '$ref' in p:
            return comp_params[ref_name(p['$ref'])]
        return p

    out = [HEADER, "import type * as T from './types.gen';", "import { request, type CallOptions } from './client';", '']
    ops_map = []
    meta = []
    fns = []
    for path, item in spec.get('paths', {}).items():
        shared = [resolve_param(p) for p in item.get('parameters', [])]
        for method in METHODS:
            op = item.get(method)
            if not op:
                continue
            op_id = op['operationId']
            Op = upper_first(op_id)
            params = {p['name']: p for p in shared}
            for p in op.get('parameters', []):
                rp = resolve_param(p)
                params[rp['name']] = rp
            path_params = [p for p in params.values() if p['in'] == 'path']
            query_params = [p for p in params.values() if p['in'] == 'query']
            # request body
            body_t = None
            body_required = False
            csv = False
            rb = op.get('requestBody')
            if rb:
                content = rb.get('content', {})
                body_required = bool(rb.get('required'))
                parts = []
                if 'application/json' in content:
                    parts.append(g.type_expr(content['application/json'].get('schema')))
                if 'text/csv' in content:
                    csv = True
                    parts.insert(0, 'string')
                body_t = ' | '.join(g.paren(p) for p in parts) if parts else 'unknown'
            # response
            resp_t = 'void'
            responses = op.get('responses', {})
            for code in ('200', '201', '202'):
                r = responses.get(code)
                if r and 'content' in r:
                    c = r['content']
                    if 'application/json' in c:
                        resp_t = g.type_expr(c['application/json'].get('schema'))
                    elif 'text/event-stream' in c or 'application/octet-stream' in c:
                        resp_t = 'string'
                    break
            # emit types
            fns.append(jsdoc(f"{op.get('summary', '')}\n\n`{method.upper()} {path}`" + (f"\n\n{op['description']}" if op.get('description') else '')))
            fns.append(f'export type {Op}Response = {resp_t};')
            if query_params:
                ql = []
                for p in query_params:
                    d = p.get('description')
                    if d:
                        ql.append(jsdoc(d, '  ').rstrip('\n'))
                    ql.append(f"  {prop_key(p['name'])}{'' if p.get('required') else '?'}: {g.type_expr(p.get('schema'), '  ')};")
                fns.append(f'export interface {Op}Query {{\n' + '\n'.join(ql) + '\n}')
            if body_t is not None:
                fns.append(f'export type {Op}Body = {body_t};')
            al = [f"  {prop_key(p['name'])}: {g.type_expr(p.get('schema'), '  ')};" for p in path_params]
            any_required = bool(path_params) or any(p.get('required') for p in query_params) or (body_t is not None and body_required)
            if query_params:
                qreq = any(p.get('required') for p in query_params)
                al.append(f"  query{'' if qreq else '?'}: {Op}Query;")
            if body_t is not None:
                al.append(f"  body{'' if body_required else '?'}: {Op}Body;")
            fns.append(f'export interface {Op}Args {{\n' + '\n'.join(al) + ('\n' if al else '') + '}')
            default = '' if any_required else ' = {}'
            pp = ', '.join(f"{prop_key(p['name'])}: args.{p['name']}" if IDENT.match(p['name']) else f"{json.dumps(p['name'])}: args[{json.dumps(p['name'])}]" for p in path_params)
            ct = "typeof args.body === 'string' ? 'text/csv' : 'application/json'" if csv else "'application/json'"
            fns.append(
                f'export function {op_id}(args: {Op}Args{default}, opts?: CallOptions): Promise<{Op}Response> {{\n'
                f"  return request<{Op}Response>({{\n"
                f"    op: '{op_id}',\n"
                f"    method: '{method.upper()}',\n"
                f"    path: '{path}',\n"
                f'    params: {{ {pp} }},\n'
                f"    query: {'args.query' if query_params else 'undefined'},\n"
                f"    body: {'args.body' if body_t is not None else 'undefined'},\n"
                f'    contentType: {ct if body_t is not None else "undefined"},\n'
                f'    ...opts,\n'
                f'  }});\n'
                f'}}\n'
            )
            ops_map.append(f'  {op_id}: {{ args: {Op}Args; response: {Op}Response }};')
            meta.append(f"  {op_id}: {{ method: '{method.upper()}', path: '{path}', tag: {json.dumps((op.get('tags') or [''])[0])} }},")
    out.append('/** Every operation: its arguments and response. The in-browser mock implements this map. */')
    out.append('export interface Ops {\n' + '\n'.join(ops_map) + '\n}\n')
    out.append('export type OperationId = keyof Ops;\n')
    out.append('export const operationMeta: Record<OperationId, { method: string; path: string; tag: string }> = {\n' + '\n'.join(meta) + '\n};\n')
    out.extend(fns)
    return '\n'.join(out)


def main() -> None:
    spec_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SPEC
    with open(spec_path, encoding='utf-8') as f:
        spec = yaml.safe_load(f)
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, 'types.gen.ts'), 'w', encoding='utf-8') as f:
        f.write(Gen(spec).types_file())
    with open(os.path.join(OUT_DIR, 'operations.gen.ts'), 'w', encoding='utf-8') as f:
        f.write(ops_file(spec))
    print(f'gen-api: wrote types.gen.ts and operations.gen.ts from {os.path.relpath(spec_path, UI)}')


if __name__ == '__main__':
    main()
